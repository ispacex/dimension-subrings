"""D5-34: write the certificates as Lean data files for group-dimension (GroupDimension/Cert1024/Data).

    python3 emit_lean.py pc1024.jsonl.gz cert1024.jsonl.gz OUTDIR [CHUNK]

One line per candidate (format: GroupDimension/Cert1024/Decode.lean):
    id m pow_0..pow_{m-1} conj_{k,l} (k<l) r a_0..a_{r-1} C (m·r·r entries, row-major)
Masks: bit j = exponent of g_{j+1} in GAP's numbering.  Chunks of CHUNK (100) lines, one file each
(Data/C00.lean, ...) with a `native_decide` check, and Data/All.lean joining them.
"""
import gzip
import json
import os
import sys


def opener(p):
    return gzip.open(p, "rt") if p.endswith(".gz") else open(p)


def mask(e):
    return sum(1 << j for j, x in enumerate(e) if x)


def line(p, c):
    m = p["m"]
    assert m == 10 and c["id"] == p["id"] and not c["error"]
    xs = [p["id"], m] + [mask(e) for e in p["pow"]]
    for k in range(m):
        assert len(p["conj"][k]) == m - k - 1
        xs += [mask(e) for e in p["conj"][k]]
    r = len(c["mods"])
    xs += [r] + c["mods"]
    for M in c["mats"]:
        assert len(M) == r and all(len(row) == r for row in M)
        for row in M:
            assert all(0 <= x < 1 << 31 for x in row)
            xs += row
    return " ".join(map(str, xs))


def main():
    pcf, cf, out = sys.argv[1:4]
    chunk = int(sys.argv[4]) if len(sys.argv) > 4 else 100
    certs = {}
    for l in opener(cf):
        c = json.loads(l)
        certs[c["id"]] = c
    lines = []
    for l in opener(pcf):
        p = json.loads(l)
        lines.append(line(p, certs[p["id"]]))
    os.makedirs(out, exist_ok=True)
    names = []
    for t in range(0, len(lines), chunk):
        name = f"C{t // chunk:02d}"
        names.append(name)
        body = ",\n  ".join(f'"{s}"' for s in lines[t:t + chunk])
        with open(os.path.join(out, name + ".lean"), "w") as f:
            f.write(f"""module

public import GroupDimension.Cert1024.Decode
public meta import Cert1024Comp

@[expose] public section

/-! Certificates for Prop. 5.3, candidates {t + 1}–{min(t + chunk, len(lines))} of {len(lines)}
(generated by `compute/cert1024/emit_lean.py` of dimension-subrings; format: `Decode.lean`). -/

namespace GroupDimension.Cert1024.Data

/-- Candidates {t + 1}–{min(t + chunk, len(lines))}. -/
def {name.lower()} : List String := [
  {body}]

/-- The check passes for every line of this chunk (evaluated by `native_decide`). -/
theorem {name.lower()}_ok : {name.lower()}.all checkStr = true := by native_decide

end GroupDimension.Cert1024.Data
""")
    imports = "\n".join(f"public import GroupDimension.Cert1024.Data.{n}" for n in names)
    joined = " ++ ".join(n.lower() for n in names)
    oks = ", ".join(f"{n.lower()}_ok" for n in names)
    with open(os.path.join(out, "All.lean"), "w") as f:
        f.write(f"""module

{imports}

@[expose] public section

/-! All {len(lines)} certificates of Prop. 5.3. -/

namespace GroupDimension.Cert1024.Data

/-- The {len(lines)} lines, in the order of `compute/pq1024/results/candidates.csv` sorted by
`(parent, k)`. -/
def cands : List String := {joined}

theorem cands_length : cands.length = {len(lines)} := by
  simp only [cands, List.length_append]; rfl

theorem cands_ok : cands.all checkStr = true := by
  simp only [cands, List.all_append, {oks}, Bool.and_self]

end GroupDimension.Cert1024.Data
""")
    print(len(lines), "lines,", len(names), "chunks")


if __name__ == "__main__":
    main()
