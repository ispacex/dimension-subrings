"""Integral dimension subgroups D_n(G) = G ∩ (1 + Δ^n) of a finite p-group, computed exactly.

Coordinates.  Z[G] = Z·1 ⊕ Δ, and Δ has the Z-basis {g - 1 : g ≠ 1}.  An element of Δ is the
vector of its coefficients at the group elements g ≠ 1 (the coefficient at 1 is minus their sum).

Arithmetic modulo D = p^E.  All lattices are taken modulo DΔ, i.e. as submodules of
Δ/DΔ ≅ (Z/p^E)^{N-1}, in Howell echelon form (see `howell`).  DΔ is a two-sided ideal, so the
image of Δ^n in Δ/DΔ is generated by the images of the products that generate Δ^n, and both
conclusions below are exact, not approximate:

  * if g - 1 is NOT in Δ^n + DΔ, then g - 1 is not in Δ^n, so g ∉ D_n(G)        (always valid);
  * if every element of p^{E-1}Δ lies in Δ^n + DΔ (`certified`), then DΔ ⊆ Δ^n, the image is
    Δ^n itself, and membership modulo D is membership in Δ^n                    (checked per n).

Construction of Δ^n (method A).  Let x_1..x_d generate G and b_1..b_r span Δ^{n-1}.  Then
Δ^n = span_Z{ b_k (x_i - 1) }.  Proof in README.md.

Method B (independent check): Δ^n = span{ (y - 1) b_k : y in S, k }, S = the union of the
conjugacy classes of a generating set (here: of a Pcgs), with no closure step.
"""
import json
import sys

import numpy as np

EMAX = {2: 30, 3: 19, 5: 13, 7: 11}   # p^E < 2^31, so products of two residues fit in int64


class Ring:
    def __init__(self, p, E=None):
        self.p = p
        self.E = E if E is not None else EMAX[p]
        self.D = p ** self.E
        self.ppow = [p ** k for k in range(self.E + 1)]

    def val(self, col):
        """p-adic valuations of the nonzero residues in col (values in [0, D))."""
        v = np.zeros(col.shape, dtype=np.int64)
        t = col.copy()
        for _ in range(self.E):
            m = (t % self.p == 0)
            if not m.any():
                break
            v += m
            t = np.where(m, t // self.p, t)
        return v


def howell(R, A):
    """Howell echelon form of the row span of A over Z/p^E.

    Returns a list of (column, valuation, row) with increasing columns, row[column] = p^valuation,
    row zero before column; every element of the span that vanishes before column c lies in the
    span of the rows with column >= c (the Howell property — see README)."""
    D, p = R.D, R.p
    A = np.asarray(A, dtype=np.int64) % D
    A = A[A.any(axis=1)]
    if A.ndim != 2 or A.shape[0] == 0:
        return []
    m = A.shape[1]
    out = []
    pending = []                               # rows p^{E-v}·pivot still to be joined to A
    since_compact = 0
    for c in range(m):
        if pending:
            A = np.vstack([A] + pending)
            pending = []
        if A.shape[0] == 0:
            break
        col = A[:, c]
        nz = np.nonzero(col)[0]
        if nz.size == 0:
            continue
        vals = R.val(col[nz])
        j = int(np.argmin(vals))
        i = int(nz[j])
        v = int(vals[j])
        pv = R.ppow[v]
        u = int(col[i]) // pv
        piv = (A[i] * pow(u, -1, D)) % D
        A[i] = 0                               # the pivot row leaves the pool
        rows = nz[nz != i]
        if rows.size:
            f = A[rows, c] // pv               # exact: valuations in the column are >= v
            A[rows, c:] = (A[rows, c:] - f[:, None] * piv[None, c:]) % D
        if v > 0:
            extra = (piv * R.ppow[R.E - v]) % D    # vanishes at column c
            if extra.any():
                pending.append(extra[None, :])
        out.append((c, v, piv))
        since_compact += 1
        if since_compact >= 16:
            A = A[A[:, c + 1:].any(axis=1)]
            since_compact = 0
    return out


def reduce_rows(R, H, X):
    """Reduce the rows of X against the Howell form H; returns a boolean mask 'row in span'."""
    D = R.D
    X = np.asarray(X, dtype=np.int64) % D
    ok = np.ones(X.shape[0], dtype=bool)
    for c, v, piv in H:
        pv = R.ppow[v]
        rows = np.nonzero(X[:, c])[0]
        if rows.size == 0:
            continue
        col = X[rows, c]
        bad = (col % pv) != 0
        ok[rows[bad]] = False
        rows, col = rows[~bad], col[~bad]
        if rows.size:
            X[rows, c:] = (X[rows, c:] - (col // pv)[:, None] * piv[None, c:]) % D
    ok &= ~X.any(axis=1)
    return ok


def rows_of(H):
    return np.array([r for _, _, r in H], dtype=np.int64) if H else None


class Group:
    def __init__(self, rec):
        self.rec = rec
        self.N = rec["order"]
        self.one = rec["one"]
        self.idx = [i for i in range(self.N) if i != self.one]      # coordinate k <-> element idx[k]
        self.gens = [np.array(a, dtype=np.int64) for a in rec["gens"]]
        self.pcgs = [np.array(a, dtype=np.int64) for a in rec["pcgs"]]
        self.lev = rec["lev"]

    def full(self, V):
        """Δ-coordinates (rows) -> Z[G]-coordinates (coefficient at 1 = -sum)."""
        F = np.zeros((V.shape[0], self.N), dtype=np.int64)
        F[:, self.idx] = V
        F[:, self.one] = -V.sum(axis=1)
        return F

    def delta(self, F):
        return F[:, self.idx]

    def right_mul(self, V, perm, D):
        """V·x for the right action perm of x (perm[i] = index of elts[i]*x)."""
        F = self.full(V) % D
        G = np.zeros_like(F)
        G[:, perm] = F
        return self.delta(G) % D

    def g_minus_1(self):
        return np.eye(self.N - 1, dtype=np.int64)


def delta_power_A(R, G, Hprev, check_ideal=False):
    """Method A: Δ^n = span{ b·(x_i - 1) : b in a basis of Δ^{n-1}, x_i in a generating set }.
    (Δ is the left ideal generated by the x_i - 1, and Δ^{n-1}·Z[G] = Δ^{n-1}; README.)
    With check_ideal, also verify at run time that the result is closed under right
    multiplication by the generators (it must be: Δ^n is an ideal)."""
    B = rows_of(Hprev)
    if B is None:
        return []
    blocks = [(G.right_mul(B, x, R.D) - B) % R.D for x in G.gens]    # b·x - b = b·(x - 1)
    H = howell(R, np.vstack(blocks))
    if check_ideal and H:
        cur = rows_of(H)
        for x in G.gens + G.pcgs:
            if not reduce_rows(R, H, G.right_mul(cur, x, R.D)).all():
                raise RuntimeError("computed Δ^n is not a right ideal")
    return H


def conj_class_union(G, gens):
    """Indices of the union of the conjugacy classes of the given generators, from the right
    actions alone: y^h = h^{-1} y h.  The right regular actions of the generators generate the
    right regular representation; we build all right-multiplication perms by BFS."""
    N = G.N
    # element index -> its right-multiplication permutation, by BFS from the identity
    perms = {G.one: np.arange(N)}
    frontier = [G.one]
    while frontier:
        nxt = []
        for e in frontier:
            for x in gens:
                # e*x: index perm_x[e]; its right action is perm_e followed by perm_x
                ex = int(x[e])
                if ex not in perms:
                    perms[ex] = x[perms[e]]
                    nxt.append(ex)
        frontier = nxt
    assert len(perms) == N
    # left multiplication by h: h*g = (right action of g applied to h)
    # y^h = h^{-1} y h. index of h^{-1}: the k with perms[h][k] = one
    S = set()
    for x in gens:
        y = int(x[G.one])            # index of the generator itself
        for h in range(N):
            hinv = int(np.nonzero(perms[h] == G.one)[0][0])
            S.add(int(perms[h][perms[y][hinv]]))   # ((h^{-1})·y)·h
    S.discard(G.one)
    return sorted(S), perms


def delta_power_B(R, G, Hprev, S, perms):
    """Method B: Δ^n = span{(y - 1)·b : y ∈ S, b ∈ basis of Δ^{n-1}}, S closed under conjugation
    and generating G.  Left multiplication by y: (y·u)[y*g] = u[g], and y*g = perms[g][y]."""
    B = rows_of(Hprev)
    if B is None:
        return []
    F = G.full(B) % R.D
    blocks = []
    for y in S:
        lperm = np.array([int(perms[g][y]) for g in range(G.N)], dtype=np.int64)  # g -> y*g
        Y = np.zeros_like(F)
        Y[:, lperm] = F
        blocks.append((G.delta(Y) - B) % R.D)
    return howell(R, np.vstack(blocks))


def certified(R, H, m):
    """True iff p^{E-1}·Δ ⊆ Δ^n + p^E Δ, which forces p^E Δ ⊆ Δ^n (README)."""
    X = np.eye(m, dtype=np.int64) * R.ppow[R.E - 1]
    return bool(reduce_rows(R, H, X).all())


def analyse(rec, nmax=6, method="A", E=None, full=False):
    """For n = 1, 2, ... compute D_n and compare it with gamma_n.

    Default (fast) mode: only the elements of D_{n-1} are tested for D_n (D_n ⊆ D_{n-1}), and
    the computation stops as soon as D_n = 1 (then D_k = 1 for all k >= n).  The exactness
    certificate is computed only when D_n ≠ gamma_n.
    full=True: every level up to nmax (and on until D_n = 1), every g tested, certificate always,
    Δ^n checked to be a right ideal — used for the cross-checks."""
    G = Group(rec)
    R = Ring(rec["p"], E)
    m = G.N - 1
    cls = rec["cls"]
    H = howell(R, G.g_minus_1())             # Δ itself
    if method == "B":
        S, perms = conj_class_union(G, G.pcgs)
    res = {"order": G.N, "id": rec["id"], "p": rec["p"], "cls": cls, "dl": rec["dl"],
           "d": len(rec["gens"]), "levels": []}
    prevD = list(range(m))                   # Δ-coordinates of the elements of D_{n-1} \ {1}
    n = 1
    while True:
        test = list(range(m)) if full else prevD
        X = np.zeros((len(test), m), dtype=np.int64)
        X[np.arange(len(test)), test] = 1      # the vectors g - 1
        inD = reduce_rows(R, H, X) if len(test) else np.zeros(0, dtype=bool)
        Dk = [test[t] for t in range(len(test)) if inD[t]]
        Dset = {G.idx[k] for k in Dk}
        gset = {G.idx[k] for k in range(m) if G.lev[G.idx[k]] >= n}
        sane = gset <= Dset                  # gamma_n ⊆ D_n must hold
        equal = Dset == gset                 # exact without certificate: non-members are certified
        cert = certified(R, H, m) if (full or not equal) else None
        logsize = sum(R.E - v for _, v, _ in H)          # log_p |image of Δ^n in Δ/DΔ|
        res["levels"].append({
            "n": n, "Dn_order": len(Dset) + 1, "gamma_order": len(gset) + 1,
            "sane": sane, "equal": equal, "certified": cert,
            "index_logp": m * R.E - logsize,   # log_p [Δ : Δ^n + DΔ]
            "extra": sorted(Dset - gset),
        })
        if not sane:
            raise RuntimeError(f"gamma_{n} not inside computed D_{n} for {rec['order']},{rec['id']}")
        if not Dset and (not full or n >= nmax):
            break
        if n >= 16:
            break
        prevD = Dk
        if method == "A":
            H = delta_power_A(R, G, H, check_ideal=full)
        else:
            H = delta_power_B(R, G, H, S, perms)
        n += 1
    return res


def main():
    method = sys.argv[1] if len(sys.argv) > 1 else "A"
    full = "--full" in sys.argv
    for line in sys.stdin:
        if line.strip():
            print(json.dumps(analyse(json.loads(line), method=method, full=full)), flush=True)


if __name__ == "__main__":
    main()
