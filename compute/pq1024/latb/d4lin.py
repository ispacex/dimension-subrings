"""MATH-415: is there a step-1 descendant Q = R*/U of a parent R with n in D_4(Q)?  (README,
"D_4 by the p-cover, linearly".)  Input: the lines of ../d4lin.g.

Let A = Z<a_1..a_d>_{<4} / J_4 = Z[R*]/Delta^4 (the Magnus algebra of the presentation of R*),
v_j = mu(m_j) - 1 for the basis m_1..m_m of the multiplicator M (central, elementary), and
J' = J_4 + the two-sided ideal generated by the v_j a_i.  Modulo J', m -> m - 1 is a homomorphism
M -> A/J' (uv - 1 = (u-1) + (v-1) + (u-1)(v-1)), and by Nakayama (V = sum (m-1)A is killed by
Delta^3) n = mU in D_4(R*/U) iff K_D is not in U, where K_D = {m in M : m - 1 in J'} is its kernel.
Modulo 2^E membership is only necessary, so the K_D computed here contains the true one, and
"no admissible U" is exact.  A hyperplane U = ker(a Y): admissible means a outside ker P for
P = PA, PB, PN (gamma_3, M_4, nucleus; gamma_4(R*) <= U is built into Y) and, for n in D_4,
P_D = K_D Y^T.  Output per parent: dim K_D, the number of a, verdict.

Usage: python d4lin.py [E] < d4lin_*.jsonl   (E = 30)."""
import json
import sys
import time
from itertools import combinations

import numpy as np

from howell import Ring, howell, reduce_rows, rows_of
from magnus_pres import Alg, J_howell, shift_rows


def close(R, A, rows):
    """Howell form of the two-sided ideal generated by rows (positive parts)."""
    H = howell(R, rows % R.D)
    while True:
        B = rows_of(H, A.M)
        if B.shape[0] == 0:
            return H
        new = shift_rows(A, B) % R.D
        new = new[new.any(axis=1)]
        if new.shape[0] == 0 or reduce_rows(R, H, new).all():
            return H
        H = howell(R, np.vstack([B, new]))


def right_gen(A, V):
    """The rows v a_i (right multiples by the generators) of the positive parts V."""
    full = np.zeros((V.shape[0], A.T), dtype=A.dt)
    full[:, 1:] = V
    out = []
    for i in range(A.d):
        Rr = np.zeros_like(full)
        for k in range(A.n - 1):
            Rr[:, A.off[k + 1] + i:A.off[k + 2]:A.d] = full[:, A.off[k]:A.off[k + 1]]
        out.append(Rr[:, 1:])
    return np.vstack(out)


def f2_rank(rows):
    K = np.array(rows, dtype=np.int64) % 2
    if K.size == 0:
        return 0
    rank = 0
    for c in range(K.shape[1]):
        piv = [i for i in range(rank, K.shape[0]) if K[i, c]]
        if not piv:
            continue
        K[[rank, piv[0]]] = K[[piv[0], rank]]
        for i in range(K.shape[0]):
            if i != rank and K[i, c]:
                K[i] ^= K[rank]
        rank += 1
    return rank


def f2_basis(rows):
    K = np.array(rows, dtype=np.int64) % 2
    out, rank = [], 0
    if K.size == 0:
        return []
    for c in range(K.shape[1]):
        piv = [i for i in range(rank, K.shape[0]) if K[i, c]]
        if not piv:
            continue
        K[[rank, piv[0]]] = K[[piv[0], rank]]
        for i in range(K.shape[0]):
            if i != rank and K[i, c]:
                K[i] ^= K[rank]
        rank += 1
    return [list(r) for r in K[:rank]]


def count_outside(k, Ps):
    """#{a in GF(2)^k : a P^T != 0 for every P in Ps} (inclusion-exclusion, as MC_CountOutside)."""
    tot = 0
    for s in range(len(Ps) + 1):
        for sub in combinations(range(len(Ps)), s):
            rows = [r for i in sub for r in Ps[i]]
            tot += (-1) ** s * 2 ** (k - f2_rank(rows))
    return tot


def kernel_basis(R, H, V, Mn):
    """K_D: {c in GF(2)^r : sum c_j v_j in J'} modulo 2^E, as a GF(2) basis (cf. kernel_rank)."""
    p, r = R.p, V.shape[0]
    top = np.hstack([rows_of(H, Mn), np.zeros((len(H), r), dtype=np.int64)])
    mid = np.hstack([V % R.D, np.eye(r, dtype=np.int64)])
    bot = np.hstack([np.zeros((r, Mn), dtype=np.int64), p * np.eye(r, dtype=np.int64)])
    Hk = howell(R, np.vstack([top, mid, bot]))
    return f2_basis([row[Mn:] for c, v, row in Hk if c >= Mn])


def analyse(rec, E):
    t0 = time.time()
    R = Ring(2, E)
    A = Alg(rec["d"], 4, R.D)
    st = {}
    H = J_howell(R, A, rec["rels"], st)
    V = np.array([A.word(w)[1:] for _, w in rec["tests"]], dtype=np.int64) % R.D
    Hp = close(R, A, np.vstack([rows_of(H, A.M), right_gen(A, V) % R.D]))
    KD = kernel_basis(R, Hp, V, A.M)
    Y = np.array(rec["Y"], dtype=np.int64)
    PD = [list((np.array(x) @ Y.T) % 2) for x in KD] if KD else []
    PD = [r for r in PD if any(r)]
    k = rec["k"]
    PA, PB, PN = rec["PA"], rec["PB"], rec["PN"]
    cnt = count_outside(k, [PA, PB, PN, PD]) if PD else 0
    cnt_d = count_outside(k, [PN, PD]) if PD else 0
    return {"id": rec["id"], "parent": rec["parent"], "rank": rec["rank"], "d": rec["d"],
            "m": rec["m"], "k": k, "count_ABN": rec["count"], "dim_KD": len(KD),
            "count_ABND": cnt, "count_ND": cnt_d,
            "verdict": "no U with n in D_4 (exact)" if cnt_d == 0 else "U WITH n in D_4 mod 2^E: check",
            "seconds": round(time.time() - t0, 3)}


def main():
    E = int(sys.argv[1]) if len(sys.argv) > 1 else 30
    for line in sys.stdin:
        if line.strip():
            print(json.dumps(analyse(json.loads(line), E)), flush=True)


if __name__ == "__main__":
    main()
