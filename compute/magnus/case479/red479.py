MOD = 27


def inv_mod(C, m):
    """inverse of the integer matrix C mod m = 3^k (C invertible mod 3)"""
    s = C.shape[0]
    M = np.concatenate([np.array(C, dtype=np.int64) % m, np.eye(s, dtype=np.int64)], axis=1)
    for c in range(s):
        p = next(i for i in range(c, s) if M[i, c] % 3)
        if p != c: M[[c, p]] = M[[p, c]]
        M[c] = (M[c] * pow(int(M[c, c]), -1, m)) % m
        for i in range(s):
            if i != c and M[i, c]: M[i] = (M[i] - M[i, c] * M[c]) % m
    return M[:, s:]


def inv3(M):
    """inverse of a small invertible matrix over F_3 (tuple of tuples) -> list of lists"""
    r = len(M)
    A = [list(M[i]) + [int(i == j) for j in range(r)] for i in range(r)]
    for c in range(r):
        p = next(i for i in range(c, r) if A[i][c] % 3)
        A[c], A[p] = A[p], A[c]
        iv = 1 if A[c][c] % 3 == 1 else 2
        A[c] = [(x * iv) % 3 for x in A[c]]
        for i in range(r):
            if i != c and A[i][c] % 3:
                f = A[i][c]; A[i] = [(a - f * b) % 3 for a, b in zip(A[i], A[c])]
    return [row[r:] for row in A]


def induced9(S, A, s):
    """S: (n, s, s) integer matrices mod 27 fixing K_3 -> (n, s, s) T9 over Z/9, row h = coordinates of S b_h in the
    basis b of K_3 / 9K_3 (row-vector convention: coords(S v) = coords(v) T9); induced9 mod 3 == induced27"""
    sc = np.array([3 if h in A else 1 for h in range(s)], dtype=np.int64)
    W = (S @ np.diag(sc)) % MOD                      # column h = S b_h
    assert not (W[:, [g for g in range(s) if g in A], :] % 3).any(), "S does not fix K_3"
    W = W // sc[None, :, None]                       # coordinate g: w_g / 3 (g in A) or w_g
    return np.transpose(W, (0, 2, 1)) % 9


class Lifts:
    """the lifts of one pair (Y, X): F_3-vectors c in (F_3^free)^dim X, indexed as in s5_472.lifts"""
    def __init__(self, Y, X, s):
        self.Y, self.X, self.s, self.r = Y, X, s, len(X)
        self.ypiv = [next(i for i, a in enumerate(y) if a) for y in Y]
        self.xpiv = [next(i for i, a in enumerate(x) if a) for x in X]
        self.free = [h for h in range(s) if h not in self.ypiv]
        self.f = len(self.free); self.dim = self.r * self.f; self.n = 3 ** self.dim
        self.Xi = np.array(X, dtype=np.int64).reshape(self.r, s)
        # all lifts as F_3 coordinate vectors (n, dim), in the order of s5_472.lifts (itertools.product, last fastest)
        self.coords = np.array(list(itertools.product(range(3), repeat=self.dim)), dtype=np.int64).reshape(self.n, self.dim)
        self.pow = 3 ** np.arange(self.dim - 1, -1, -1, dtype=np.int64)

    def c_full(self, coords):
        """(m, dim) -> (m, r, s): c_j with the free coordinates filled in"""
        m = coords.shape[0]; C = np.zeros((m, self.r, self.s), dtype=np.int64)
        for j in range(self.r):
            for k, h in enumerate(self.free): C[:, j, h] = coords[:, j * self.f + k]
        return C

    def c_tuple(self, idx):
        """index -> the c of s5_472.lifts (tuple of length-s lists)"""
        C = self.c_full(self.coords[[idx]])[0]
        return tuple(list(map(int, C[j])) for j in range(self.r))

    def image(self, T9, coords):
        """the lifts coords (m, dim) under T9 (Z/9, fixing (Y, X) mod 3) -> image coords (m, dim)"""
        r, s = self.r, self.s
        V = (self.Xi[None] + 3 * self.c_full(coords)) % 9            # (m, r, s): x_j + 3c_j
        W = (V @ T9) % 9                                              # the images of the generators of H
        M = tuple(tuple(int(W[0, j, p]) % 3 for p in self.xpiv) for j in range(r))   # x_j T = sum_k M_jk x_k
        N = np.array(inv3(M), dtype=np.int64).reshape(r, r)
        Z = np.einsum('kj,mjs->mks', N, W) % 9                        # lifts of x_k in the image
        D = (Z - self.Xi[None]) % 9
        assert not (D % 3).any(), "T9 does not fix X"
        Cn = (D // 3) % 3
        for y, p in zip(self.Y, self.ypiv):                         # reduce mod Y (3Y lies in the image)
            Cn = (Cn - Cn[:, :, p:p + 1] * np.array(y, dtype=np.int64)[None, None, :]) % 3
        out = np.zeros((coords.shape[0], self.dim), dtype=np.int64)
        for j in range(r):
            for k, h in enumerate(self.free): out[:, j * self.f + k] = Cn[:, j, h]
        return out

    def affine(self, T9):
        """the map c -> c' as (L, b) over F_3 (row convention: c' = c L + b), from 1 + dim points"""
        T3 = T9 % 3
        assert rref3([[int(sum(y[h] * T3[h, g] for h in range(self.s))) % 3 for g in range(self.s)] for y in self.Y],
                     self.s) == tuple(self.Y), "T9 does not fix Y"
        pts = np.vstack([np.zeros((1, self.dim), dtype=np.int64), np.eye(self.dim, dtype=np.int64)])
        im = self.image(T9, pts)
        b = im[0]; L = (im[1:] - b[None]) % 3
        return L, b

    def index(self, coords):
        return coords @ self.pow


def stab_T9(sp, gens27, gperm, A, s, rep, orbit_of, want_S=False):
    """Schreier elements of the stabiliser of pair 'rep' as T9 matrices (unique); also checks that the BFS orbit is
    the orbit of orbit_reps (orbit_of: pair -> its representative)"""
    U = {rep: np.eye(s, dtype=np.int64)}; Ui = {rep: np.eye(s, dtype=np.int64)}
    order = [rep]; k = 0
    while k < len(order):
        p = order[k]; k += 1
        for (C, Ci), P in zip(gens27, gperm):
            q = P[p]
            if q not in U:
                U[q] = (C @ U[p]) % MOD; Ui[q] = (Ui[p] @ Ci) % MOD; order.append(q)
    assert all(orbit_of[q] == rep for q in order), "BFS orbit differs from orbit_reps"
    Up = np.stack([U[p] for p in order]); out = []; Ss = []
    for (C, Ci), P in zip(gens27, gperm):
        Uq_inv = np.stack([Ui[P[p]] for p in order])
        S = np.einsum('nab,bc,ncd->nad', Uq_inv, C, Up) % MOD
        if want_S: Ss.append(S)
        T9 = induced9(S, A, s).reshape(len(S), -1)
        out.append(np.unique(T9, axis=0))           # deduplicated per generator: memory O(orbit)
    T9u = np.unique(np.concatenate(out), axis=0).reshape(-1, s, s)
    return T9u, len(order), (np.concatenate(Ss) if want_S else None)


class Reducer:
    """per (d, A): the pair orbits and, for each non-elementary representative, its lift orbits"""
    def __init__(self, sp, d, A):
        self.sp, self.d, self.A, self.s = sp, list(d), set(A), len(d)
        s = self.s
        self.reps, _ = orbit_reps(sp, self.d, self.A)
        Cis = gen_mats(self.d, self.A, MOD)
        self.gens27 = [(np.array(Ci, dtype=np.int64) % MOD, inv_mod(Ci, MOD)) for Ci in Cis]
        self.ngens = len(self.gens27)
        self.gperm = [sp.perm(induced27(C, self.A, s)) for C, _ in self.gens27]
        # pair permutations: subspace perm applied to (i, j)
        self.pperm = [[sp.pidx[(P[i], P[j])] for (i, j) in sp.pairs] for P in self.gperm]
        # orbit_of via union of pperm (the same partition as orbit_reps; checked in stab_T9)
        parent = list(range(len(sp.pairs)))
        def find(x):
            while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
            return x
        for P in self.pperm:
            for t, u in enumerate(P):
                a, b = find(t), find(u)
                if a != b:
                    if a < b: parent[b] = a
                    else: parent[a] = b
        self.orbit_of = [find(t) for t in range(len(sp.pairs))]
        assert sorted(set(self.orbit_of)) == self.reps
        self.nonel = [t for t in self.reps if len(sp.subs[sp.pairs[t][0]]) != s]

    def lift_orbits(self, t):
        """for the representative t: (Lifts object, sorted list of lift-orbit representatives (indices), orbit label
        per lift, number of distinct affine maps)"""
        sp, s = self.sp, self.s
        i, j = sp.pairs[t]; Y, X = sp.subs[i], sp.subs[j]
        L = Lifts(Y, X, s)
        if L.n == 1: return L, [0], np.zeros(1, dtype=np.int64), 0
        T9s, _, _ = stab_T9(sp, self.gens27, self.pperm, self.A, s, t, self.orbit_of)
        maps = set()
        for T9 in T9s:
            Lm, b = L.affine(T9)
            maps.add((Lm.tobytes(), b.tobytes()))
        parent = np.arange(L.n)
        def find(x):
            while parent[x] != x: parent[x] = parent[parent[x]]; x = parent[x]
            return x
        for Lb, bb in sorted(maps):
            Lm = np.frombuffer(Lb, dtype=np.int64).reshape(L.dim, L.dim); b = np.frombuffer(bb, dtype=np.int64)
            img = L.index((L.coords @ Lm + b[None]) % 3)
            for a, c in enumerate(img.tolist()):
                ra, rc = find(a), find(c)
                if ra != rc:
                    if ra < rc: parent[rc] = ra
                    else: parent[ra] = rc
        lab = np.array([find(a) for a in range(L.n)], dtype=np.int64)
        return L, sorted(set(lab.tolist())), lab, len(maps)


def check_lift(M, L, A, s, idx):
    return M.check({3: K3(s, A), 27: chain_K27(L.Y, L.X, L.c_tuple(idx), A, s)})


def run_A_reduced(red, M, part=0, nparts=1, fails=None):
    """the non-elementary pair orbits with index = part mod nparts (in the order of red.nonel); -> dict of counts"""
    s, A = red.s, red.A
    nl = no = nchk = nsig = nfail = nmaps = 0
    for k, t in enumerate(red.nonel[part::nparts]):
        L, reps, _, nm = red.lift_orbits(t)
        nl += L.n; no += len(reps); nmaps += nm
        for a in reps:
            ok, nz = check_lift(M, L, A, s, a)
            nchk += 1; nsig += bool(nz)
            if not ok:
                nfail += 1
                if fails is not None and len(fails) < 20: fails.append([t, a])
    return {'pair_orbits': len(red.reps), 'nonelem_orbits': len(red.nonel), 'lifts': nl, 'lift_orbits': no,
            'checked': nchk, 'sigma_nonzero': nsig, 'failing': nfail, 'maps': nmaps}


def run_A_full(red, M, part=0, nparts=1, fails=None):
    """MATH-472's run: every lift of every non-elementary representative (index = part mod nparts)"""
    s, A = red.s, red.A
    nl = nsig = nfail = 0
    for t in red.nonel[part::nparts]:
        i, j = red.sp.pairs[t]; Y, X = red.sp.subs[i], red.sp.subs[j]
        it, n = lifts(Y, X, s)
        for a, c in enumerate(it):
            ok, nz = M.check({3: K3(s, A), 27: chain_K27(Y, X, c, A, s)})
            nl += 1; nsig += bool(nz)
            if not ok:
                nfail += 1
                if fails is not None and len(fails) < 20: fails.append([t, a])
    return {'pair_orbits': len(red.reps), 'nonelem_orbits': len(red.nonel), 'lifts': nl, 'lift_orbits': nl,
            'checked': nl, 'sigma_nonzero': nsig, 'failing': nfail}


def parse_A(x):
    return set(int(a) for a in x.split(',') if a not in ('', '-'))


def all_As(s):
    return [set(c) for r in range(s + 1) for c in itertools.combinations(range(s), r)]


if __name__ == '__main__':
    mode = sys.argv[1]
    if mode == 'types':
        S = int(sys.argv[2])
        for d in capped_types_k(S, 3):
            if 9 not in d: print(",".join(map(str, d)))
        sys.exit(0)
    d = [int(a) for a in sys.argv[2].split(',')]; s = len(d)
    assert 9 not in d and d == sorted(d)
    t0 = time.time()
    if mode == 'run':
        rest = sys.argv[3:]
        if rest and rest[0] != 'all' and rest[0] not in ('D2', 'Kt'):
            As = [parse_A(rest[0])]; rest = rest[1:]
        else:
            As = all_As(s)
            if rest and rest[0] == 'all': rest = rest[1:]
        drop = tuple(rest)
        sp = Space(s); M = Model(d, MOD, drop)
        tot = {}
        for A in As:
            ta = time.time()
            red = Reducer(sp, d, A)
            r = run_A_reduced(red, M)
            print("  A", sorted(A), "pair-orbits", r['pair_orbits'], "non-elem", r['nonelem_orbits'], "lifts", r['lifts'],
                  "lift-orbits", r['lift_orbits'], "sigma!=0", r['sigma_nonzero'], "FAILING", r['failing'],
                  "maps", r['maps'], "sec %.1f" % (time.time() - ta), flush=True)
            for k, v in r.items(): tot[k] = tot.get(k, 0) + v
        print("S5NER type", ",".join(map(str, d)), "drop", sorted(drop), "A", len(As), "pair-orbits", tot['pair_orbits'],
              "non-elem-orbits", tot['nonelem_orbits'], "lifts", tot['lifts'], "lift-orbits", tot['lift_orbits'],
              "sigma!=0", tot['sigma_nonzero'], "sec %.1f" % (time.time() - t0), "FAILING", tot['failing'], flush=True)
        sys.exit(0 if drop else (1 if tot['failing'] else 0))
    if mode == 'cmp':
        A = parse_A(sys.argv[3]); drop = tuple(sys.argv[4:])
        sp = Space(s); M = Model(d, MOD, drop); red = Reducer(sp, d, A)
        nl = no = nf_full = nf_red = mixed = bad = 0
        for t in red.nonel:
            L, reps, lab, _ = red.lift_orbits(t)
            verd = [check_lift(M, L, A, s, a)[0] for a in range(L.n)]
            nl += L.n; no += len(reps)
            nf_full += sum(not v for v in verd); nf_red += sum(not verd[a] for a in reps)
            # every orbit: members' verdicts vs the representative's
            for a in range(L.n):
                if verd[a] != verd[int(lab[a])]: mixed += 1
            # an orbit with a failing member must have a failing representative (else the reduction loses it)
            failing_orbits = {int(lab[a]) for a in range(L.n) if not verd[a]}
            bad += sum(1 for o in failing_orbits if verd[o])
        print("S5NECMP type", ",".join(map(str, d)), "A", ",".join(map(str, sorted(A))) or "-", "drop", sorted(drop), "non-elem", len(red.nonel),
              "lifts", nl, "lift-orbits", no, "failing-full", nf_full, "failing-reduced", nf_red,
              "mixed-members", mixed, "lost-orbits", bad, "sec %.1f" % (time.time() - t0), flush=True)
        if drop: sys.exit(0)
        sys.exit(1 if (nf_full or nf_red or bad) else 0)
    if mode == 'act':
        A = parse_A(sys.argv[3]); N = int(sys.argv[4]); rng = random.Random(int(sys.argv[5]))
        sp = Space(s); red = Reducer(sp, d, A)
        cand = [t for t in red.nonel if Lifts(sp.subs[sp.pairs[t][0]], sp.subs[sp.pairs[t][1]], s).n > 1]
        nbad = nchk = nmove = 0
        K3l = K3(s, A)
        for _ in range(N):
            t = rng.choice(cand)
            i, j = sp.pairs[t]; L = Lifts(sp.subs[i], sp.subs[j], s)
            _, _, S = stab_T9(sp, red.gens27, red.pperm, red.A, s, t, red.orbit_of, want_S=True)
            k = rng.randrange(len(S)); Sk = S[k]
            T9 = induced9(Sk[None], red.A, s)[0]
            a = rng.randrange(L.n)
            c_aff = L.coords[[a]] @ L.affine(T9)[0] % 3
            c_aff = (c_aff + L.affine(T9)[1][None]) % 3
            c_dir = L.image(T9, L.coords[[a]])
            b = int(L.index(c_dir)[0]); nmove += (b != a)
            ok_aff = (c_aff == c_dir).all()
            # independent: the lattice of lift a, mapped by the integer matrix Sk, vs the lattice of lift b
            G = chain_K27(L.Y, L.X, L.c_tuple(a), red.A, s)
            img = [(Sk @ v) % MOD for v in G]
            ok_hnf = hnf_key(img, s, MOD) == hnf_key(chain_K27(L.Y, L.X, L.c_tuple(b), red.A, s), s, MOD)
            ok_k3 = hnf_key([(Sk @ v) % MOD for v in K3l], s, MOD) == hnf_key(K3l, s, MOD)
            nchk += 1; nbad += (not (ok_aff and ok_hnf and ok_k3))
        print("S5NEACT type", ",".join(map(str, d)), "A", ",".join(map(str, sorted(A))) or "-", "samples", nchk, "moved", nmove, "mismatch", nbad,
              "sec %.1f" % (time.time() - t0), flush=True)
        sys.exit(1 if nbad else 0)
    sys.exit('unknown mode ' + mode)
