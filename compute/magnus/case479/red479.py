#!/usr/bin/env python3
"""MATH-479 (wiki 891 Sec. 18.4-18.5): the s = 5 check of MATH-472 (non-elementary chains mod 27 on capped types
WITHOUT the invariant 9) with the orbit reduction carried down to the lifts.

Setting (case472/s5_472.py).  A subgroup H = K_27/9K_3 of K_3/9K_3 = (Z/9)^s (basis b_h = e_h for h in N, 3e_h for
h in A) is (Y >= X, c): Y = {y : 3y~ in H}, X = H mod 3, and lifts x_j + 3c_j of the RREF basis x_j of X with c_j
in F_3^s / Y (written on the non-pivot coordinates of the RREF of Y).  MATH-472 took one representative (Y, X) of
each orbit of pairs under the changes of basis fixing A (case467 gen_mats, acting through case473.induced27) and
checked ALL its lifts c.

Reduction (this file).  The stabiliser G_(Y,X) of the pair in the group G generated by gen_mats acts on the lifts of
(Y, X), and R = 0 has to be checked on one lift per G_(Y,X)-orbit (the members of an orbit are the same group in
another adapted basis; D_5 is an invariant of the group -- the argument of Sec. 17.1).  Elements of G_(Y,X) are
obtained by Schreier's lemma: a BFS over the orbit of (Y, X) on pairs with the generators C_i (as integer matrices
mod 27 on Z^s, column convention K -> C K) gives transversal elements U_p with U_p (Y,X) = p, and for every pair p
and generator C, S = U_{Cp}^{-1} C U_p fixes (Y, X).  All of them together generate G_(Y,X); any subset is still
SOUND (only fewer merges, more checks).  Each S acts on (Z/9)^s by T9 = induced9(S) (rows: coordinates of S b_h),
and on the lifts by an AFFINE map of F_3^(dim X * #free) (computed on 1 + dim X * #free points, deduplicated), and the
lift orbits are the components of the union of these maps.  The representative of a lift orbit is its least index
in the enumeration order of s5_472.lifts.

Modes:
  run TYPE [A|all] [DROP]   as 's5_472.py run', with the reduction: per A 'pair-orbits P non-elem N lifts L
                            lift-orbits O sigma!=0 Z FAILING F'; summary line S5NER.  DROP (D2/Kt): control.
  cmp TYPE A [DROP]         the control of the reduction: every lift of every non-elementary pair orbit checked
                            (MATH-472's run) AND the reduced run; prints both and the number of lift orbits whose
                            members do not all have the verdict of their representative ('mixed'); exit 1 if the
                            unreduced and reduced runs disagree on any orbit, or (without DROP) anything fails.
  act TYPE A N SEED         the control of the action: N random (pair orbit, Schreier element, lift); the image of
                            the lattice K_27 under the integer matrix S (HNF, case467.hnf_key) must equal the lattice
                            of the lift the affine map gives; also the affine map against a direct evaluation.
  types S                   capped types of length S without the invariant 9 (as nonel472.py types)
"""
